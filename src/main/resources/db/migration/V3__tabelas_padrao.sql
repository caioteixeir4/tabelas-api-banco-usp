-- V3: demais tabelas padrao (ENDERECO, CONTATO, EMPRESA, FILIAL, SOCIO).
--
-- Chaves estrangeiras SEM cascade de proposito: o banco recusa apagar um pai que ainda tem filhos
-- (ORA-02292) e a API responde com um 409 claro antes de chegar la. Documentos e telefones
-- chegam normalizados (so digitos); os CHECKs abaixo sao a ultima barreira de formato e tamanho,
-- nao o lugar onde a regra de negocio mora.

CREATE TABLE ENDERECO (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    CLIENTE_ID      NUMBER        NOT NULL,
    LOGRADOURO      VARCHAR2(200) NOT NULL,
    NUMERO          VARCHAR2(20),
    COMPLEMENTO     VARCHAR2(100),
    BAIRRO          VARCHAR2(100),
    CIDADE          VARCHAR2(100) NOT NULL,
    UF              VARCHAR2(2)   NOT NULL,
    CEP             VARCHAR2(8)   NOT NULL,
    PRINCIPAL       BOOLEAN       DEFAULT FALSE NOT NULL,
    CRIADO_EM       TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ENDERECO PRIMARY KEY (ID),
    CONSTRAINT FK_ENDERECO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT CK_ENDERECO_UF  CHECK (REGEXP_LIKE(UF, '^[A-Z]{2}$')),
    CONSTRAINT CK_ENDERECO_CEP CHECK (REGEXP_LIKE(CEP, '^[0-9]{8}$'))
);
CREATE INDEX IX_ENDERECO_CLIENTE ON ENDERECO (CLIENTE_ID);

CREATE TABLE CONTATO (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    CLIENTE_ID      NUMBER        NOT NULL,
    NOME            VARCHAR2(150) NOT NULL,
    EMAIL           VARCHAR2(150),
    TELEFONE        VARCHAR2(11),
    PRINCIPAL       BOOLEAN       DEFAULT FALSE NOT NULL,
    CRIADO_EM       TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTATO PRIMARY KEY (ID),
    CONSTRAINT FK_CONTATO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT CK_CONTATO_TELEFONE CHECK (TELEFONE IS NULL OR REGEXP_LIKE(TELEFONE, '^[0-9]{10,11}$'))
);
CREATE INDEX IX_CONTATO_CLIENTE ON CONTATO (CLIENTE_ID);

CREATE TABLE EMPRESA (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    CLIENTE_ID      NUMBER        NOT NULL,
    CNPJ            VARCHAR2(14)  NOT NULL,
    RAZAO_SOCIAL    VARCHAR2(200) NOT NULL,
    NOME_FANTASIA   VARCHAR2(200),
    ATIVA           BOOLEAN       DEFAULT TRUE NOT NULL,
    CRIADO_EM       TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EMPRESA PRIMARY KEY (ID),
    CONSTRAINT UK_EMPRESA_CNPJ UNIQUE (CNPJ),
    CONSTRAINT FK_EMPRESA_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT CK_EMPRESA_CNPJ CHECK (REGEXP_LIKE(CNPJ, '^[0-9]{14}$'))
);
CREATE INDEX IX_EMPRESA_CLIENTE ON EMPRESA (CLIENTE_ID);

CREATE TABLE FILIAL (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    EMPRESA_ID      NUMBER        NOT NULL,
    CNPJ            VARCHAR2(14)  NOT NULL,
    NOME            VARCHAR2(150) NOT NULL,
    ATIVA           BOOLEAN       DEFAULT TRUE NOT NULL,
    CRIADO_EM       TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FILIAL PRIMARY KEY (ID),
    CONSTRAINT UK_FILIAL_CNPJ UNIQUE (CNPJ),
    CONSTRAINT FK_FILIAL_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA (ID),
    CONSTRAINT CK_FILIAL_CNPJ CHECK (REGEXP_LIKE(CNPJ, '^[0-9]{14}$'))
);
CREATE INDEX IX_FILIAL_EMPRESA ON FILIAL (EMPRESA_ID);

CREATE TABLE SOCIO (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    EMPRESA_ID      NUMBER        NOT NULL,
    NOME            VARCHAR2(150) NOT NULL,
    CPF             VARCHAR2(11)  NOT NULL,
    PARTICIPACAO    NUMBER(5,2)   NOT NULL,
    CRIADO_EM       TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SOCIO PRIMARY KEY (ID),
    CONSTRAINT UK_SOCIO_EMPRESA_CPF UNIQUE (EMPRESA_ID, CPF),
    CONSTRAINT FK_SOCIO_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA (ID),
    CONSTRAINT CK_SOCIO_CPF CHECK (REGEXP_LIKE(CPF, '^[0-9]{11}$')),
    CONSTRAINT CK_SOCIO_PARTICIPACAO CHECK (PARTICIPACAO > 0 AND PARTICIPACAO <= 100)
);
CREATE INDEX IX_SOCIO_EMPRESA ON SOCIO (EMPRESA_ID);
